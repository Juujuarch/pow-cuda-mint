def read_gpu_solution(worker: subprocess.Popen[str]) -> tuple[int, bytes]:
    """Read only `solution ... verified=true` from universal-cuda-miner."""
    assert worker.stdout is not None
    while line := worker.stdout.readline():
        if line.startswith("solution ") and "verified=true" in line:
            fields = dict(item.split("=", 1) for item in line.split() if "=" in item)
            return int(fields["nonce"], 16), bytes.fromhex(fields["digest"][2:])
    raise RuntimeError("CUDA worker stopped before a verified solution")


def simulate_mint(rpc: Rpc, sender: str, calldata: str, value_wei: int = 0) -> None:
    tx = {"from": sender, "to": CONTRACT, "data": calldata}
    if value_wei:
        tx["value"] = hex(value_wei)
    rpc.eth_call(tx)


def broadcast_mint(rpc: Rpc, account: Any, calldata: str, value_wei: int = 0) -> str:
    """Sign locally, broadcast only after `simulate_mint` succeeds."""
    nonce = int(rpc.call("eth_getTransactionCount", [account.address, "pending"]), 16)
    chain_id = int(rpc.call("eth_chainId", []), 16)
    gas_price = int(rpc.call("eth_gasPrice", []), 16)
    tx = {"to": CONTRACT, "data": calldata, "value": value_wei, "nonce": nonce,
          "chainId": chain_id, "gas": 500_000, "gasPrice": gas_price}
    signed = account.sign_transaction(tx)
    return rpc.call("eth_sendRawTransaction", [signed.raw_transaction.hex()])


