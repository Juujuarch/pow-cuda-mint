def k256(data: bytes) -> bytes:
    h = keccak.new(digest_bits=256)
    h.update(data)
    return h.digest()


def selector(signature: str) -> str:
    return "0x" + k256(signature.encode()).hex()[:8]


class Rpc:
    def __init__(self, url: str):
        self.url, self.session, self.request_id = url, requests.Session(), 0

    def call(self, method: str, params: list[Any]) -> Any:
        self.request_id += 1
        response = self.session.post(self.url, json={"jsonrpc": "2.0", "id": self.request_id,
            "method": method, "params": params}, timeout=15)
        response.raise_for_status()
        body = response.json()
        if "error" in body:
            raise RuntimeError(f"{method}: {body['error']}")
        return body["result"]

    def eth_call(self, tx: dict[str, str]) -> str:
        return self.call("eth_call", [tx, "latest"])


